"""Export the data of every web viewer from OpenBeam into ``web/build/data/<beam id>.js``.

Run:
    python web/export.py                  # all beams
    python web/export.py chiral-vector    # some of them
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from exporters import EXPORTERS

OUT_DIR = Path(__file__).parent / "build" / "data"


def main(ids: list[str]) -> None:
    unknown = set(ids) - set(EXPORTERS)
    if unknown:
        sys.exit(f"unknown beam id(s): {', '.join(sorted(unknown))}; known: {', '.join(EXPORTERS)}")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for beam_id in ids or EXPORTERS:
        out = OUT_DIR / f"{beam_id}.js"
        data = json.dumps(EXPORTERS[beam_id](), separators=(",", ":"))
        out.write_text(f"// Generated by web/export.py, do not edit.\nwindow.BEAM_DATA = {data};\n")
        print(f"{out}  {out.stat().st_size / 1e3:.0f} kB")


if __name__ == "__main__":
    main(sys.argv[1:])
